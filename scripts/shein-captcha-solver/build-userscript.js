'use strict';

// 由扩展 src/ 共享源码拼装 Tampermonkey userscript（与 OTP 助手同模式：扩展为规范源）。
const fs = require('node:fs');
const path = require('node:path');

const scriptDir = __dirname;
const repoRoot = path.resolve(scriptDir, '..', '..');
const extensionDir = path.join(repoRoot, 'extensions', 'xynigo-shein-captcha-solver');
const manifest = JSON.parse(fs.readFileSync(path.join(extensionDir, 'manifest.json'), 'utf8'));
const outputPath = path.join(scriptDir, 'xynigo_shein_captcha_solver.user.js');
const rawUrl = 'https://raw.githubusercontent.com/wrangler1024/crossborder-userscripts/main/scripts/shein-captcha-solver/xynigo_shein_captcha_solver.user.js';

const read = (relativePath) => fs.readFileSync(path.join(extensionDir, relativePath), 'utf8').trim();
const runtime = fs.readFileSync(path.join(scriptDir, 'userscript-runtime.js'), 'utf8').trim();

const header = `// ==UserScript==
// @name         Xynigo SHEIN Captcha Auto Solver
// @namespace    https://github.com/wrangler1024/crossborder-userscripts
// @version      ${manifest.version}
// @description  选品过程中按页面规则自动处理 SHEIN nine-captcha 九宫格验证码：视觉模型可配置（智谱/豆包/Gemini/自定义），支持双模型对比与样本回放。
// @author       Samforo
// @homepageURL  https://github.com/wrangler1024/crossborder-userscripts/tree/main/scripts/shein-captcha-solver
// @supportURL   https://github.com/wrangler1024/crossborder-userscripts/issues
// @match        https://us.shein.com/*
// @match        https://shein.com.mx/*
// @match        https://*.shein.com.mx/*
// @icon         https://raw.githubusercontent.com/wrangler1024/crossborder-userscripts/main/assets/xynigo-mascot.png
// @grant        GM_xmlhttpRequest
// @grant        GM_registerMenuCommand
// @connect      open.bigmodel.cn
// @connect      ark.cn-beijing.volces.com
// @connect      generativelanguage.googleapis.com
// @connect      us.shein.com
// @connect      *.shein.com
// @connect      shein.com.mx
// @connect      *.shein.com.mx
// @connect      *.ltwebstatic.com
// @run-at       document-idle
// @downloadURL  ${rawUrl}
// @updateURL    ${rawUrl}
// ==/UserScript==`;

const output = [
    header,
    '',
    '// Generated from the shared Manifest V3 source. Do not edit this file by hand.',
    `globalThis.__xynigoCaptchaVersion = ${JSON.stringify(manifest.version)};`,
    runtime,
    '',
    read('src/config.js'),
    '',
    read('src/puzzle.js'),
    '',
    read('src/vision-client.js'),
    '',
    read('src/stats.js'),
    '',
    read('src/captcha-agent.js'),
    '',
    'globalThis.XynigoCaptchaUserscriptRuntime.install();',
    '',
    read('src/content.js'),
    '',
].join('\n');

fs.writeFileSync(outputPath, output, 'utf8');
process.stdout.write(outputPath + '\n');
