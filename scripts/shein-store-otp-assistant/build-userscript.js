'use strict';

const fs = require('node:fs');
const path = require('node:path');

const scriptDir = __dirname;
const repoRoot = path.resolve(scriptDir, '..', '..');
const extensionDir = path.join(repoRoot, 'extensions', 'xynigo-shein-store-otp-assistant');
const manifest = JSON.parse(fs.readFileSync(path.join(extensionDir, 'manifest.json'), 'utf8'));
const runtime = fs.readFileSync(path.join(scriptDir, 'userscript-runtime.js'), 'utf8').trim();
const core = fs.readFileSync(path.join(extensionDir, 'src', 'otp-core.js'), 'utf8').trim();
const pageState = fs.readFileSync(path.join(extensionDir, 'src', 'page-state.js'), 'utf8').trim();
const content = fs.readFileSync(path.join(extensionDir, 'src', 'content.js'), 'utf8').trim();
const css = fs.readFileSync(path.join(extensionDir, 'src', 'content.css'), 'utf8');
const outputPath = path.join(scriptDir, 'xynigo_shein_store_otp_assistant.user.js');
const rawUrl = 'https://raw.githubusercontent.com/wrangler1024/crossborder-userscripts/main/scripts/shein-store-otp-assistant/xynigo_shein_store_otp_assistant.user.js';

const header = `// ==UserScript==
// @name         Xynigo SHEIN 店铺接码助手
// @namespace    https://github.com/wrangler1024/crossborder-userscripts
// @version      ${manifest.version}
// @description  SHEIN 登录发码后自动轮询店铺接码链接并填入验证码，确认登录仍由运营人员手动完成。
// @author       Samforo
// @homepageURL  https://github.com/wrangler1024/crossborder-userscripts/tree/main/scripts/shein-store-otp-assistant
// @supportURL   https://github.com/wrangler1024/crossborder-userscripts/issues
// @match        https://sellerhub.shein.com/*
// @icon         https://raw.githubusercontent.com/wrangler1024/crossborder-userscripts/main/assets/xynigo-mascot.png
// @grant        GM_getValue
// @grant        GM_setValue
// @grant        GM_deleteValue
// @grant        GM_addStyle
// @grant        GM_registerMenuCommand
// @grant        GM_xmlhttpRequest
// @connect      api.68sms.com
// @run-at       document-start
// @noframes
// @downloadURL  ${rawUrl}
// @updateURL    ${rawUrl}
// ==/UserScript==`;

const output = [
  header,
  '',
  '// Generated from the shared Manifest V3 source. Do not edit this file by hand.',
  runtime,
  '',
  core,
  '',
  pageState,
  '',
  `globalThis.XynigoSheinOtpUserscriptRuntime.boot(globalThis, ${JSON.stringify(css)}, ${JSON.stringify(manifest.version)}, globalThis.XynigoSheinOtpUserscriptRuntime.browserAdapters());`,
  '',
  content,
  '',
].join('\n');

fs.writeFileSync(outputPath, output, 'utf8');
process.stdout.write(`${outputPath}\n`);
