'use strict';

const fs = require('node:fs');
const path = require('node:path');

const scriptDir = __dirname;
const repoRoot = path.resolve(scriptDir, '..', '..');
const extensionDir = path.join(repoRoot, 'extensions', 'xynigo-dxm-logistics-assistant');
const manifest = JSON.parse(fs.readFileSync(path.join(extensionDir, 'manifest.json'), 'utf8'));
const vendor = fs.readFileSync(path.join(extensionDir, 'vendor', 'jszip.min.js'), 'utf8').trim();
const core = fs.readFileSync(path.join(extensionDir, 'src', 'core.js'), 'utf8').trim();
const importTools = fs.readFileSync(path.join(extensionDir, 'src', 'import.js'), 'utf8').trim();
const templateData = fs.readFileSync(path.join(extensionDir, 'src', 'template-data.js'), 'utf8').trim();
const content = fs.readFileSync(path.join(extensionDir, 'src', 'content.js'), 'utf8').trim();
const css = fs.readFileSync(path.join(extensionDir, 'src', 'content.css'), 'utf8');
const icon48 = fs.readFileSync(path.join(extensionDir, 'icons', 'icon48.png')).toString('base64');
const outputPath = path.join(scriptDir, 'xynigo_dxm_logistics_assistant.user.js');
const rawUrl = 'https://raw.githubusercontent.com/wrangler1024/crossborder-userscripts/main/scripts/dxm-logistics-assistant/xynigo_dxm_logistics_assistant.user.js';

const header = `// ==UserScript==
// @name         Xynigo 店小秘物流助手
// @namespace    https://github.com/wrangler1024/crossborder-userscripts
// @version      ${manifest.version}
// @description  在店小秘待处理订单页导入物流信息，经预检确认后执行首次发货或 SHEIN 拆单分批发货。
// @author       Samforo
// @homepageURL  https://github.com/wrangler1024/crossborder-userscripts/tree/main/scripts/dxm-logistics-assistant
// @supportURL   https://github.com/wrangler1024/crossborder-userscripts/issues
// @match        https://dianxiaomi.com/web/order/approved*
// @match        https://*.dianxiaomi.com/web/order/approved*
// @icon         https://raw.githubusercontent.com/wrangler1024/crossborder-userscripts/main/extensions/xynigo-dxm-logistics-assistant/icons/icon48.png
// @grant        none
// @run-at       document-idle
// @noframes
// @downloadURL  ${rawUrl}
// @updateURL    ${rawUrl}
// ==/UserScript==`;

const bootstrap = `(function installXynigoDxmLogisticsUserscriptAssets(root) {
  'use strict';
  root.XynigoDxmLogisticsAssets = Object.freeze({
    icon48: ${JSON.stringify(`data:image/png;base64,${icon48}`)},
  });
  const style = document.createElement('style');
  style.dataset.xynigoDxmLogistics = 'userscript';
  style.textContent = ${JSON.stringify(css)};
  (document.head || document.documentElement).appendChild(style);
})(globalThis);`;

const output = [
  header,
  '',
  '// Generated from the shared Manifest V3 source. Do not edit this file by hand.',
  bootstrap,
  '',
  vendor,
  '',
  core,
  '',
  importTools,
  '',
  templateData,
  '',
  content,
  '',
].join('\n');

fs.writeFileSync(outputPath, output, 'utf8');
process.stdout.write(`${outputPath}\n`);
