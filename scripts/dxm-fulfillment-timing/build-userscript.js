'use strict';

const fs = require('node:fs');
const path = require('node:path');

const scriptDir = __dirname;
const repoRoot = path.resolve(scriptDir, '..', '..');
const extensionDir = path.join(repoRoot, 'extensions', 'xynigo-dxm-fulfillment-timing');
const manifest = JSON.parse(fs.readFileSync(path.join(extensionDir, 'manifest.json'), 'utf8'));
const runtime = fs.readFileSync(path.join(scriptDir, 'userscript-runtime.js'), 'utf8').trim();
const core = fs.readFileSync(path.join(extensionDir, 'src', 'core.js'), 'utf8').trim();
const inject = fs.readFileSync(path.join(extensionDir, 'src', 'inject.js'), 'utf8').trim();
const content = fs.readFileSync(path.join(extensionDir, 'src', 'content.js'), 'utf8').trim();
const css = fs.readFileSync(path.join(extensionDir, 'src', 'panel.css'), 'utf8');
const outputPath = path.join(scriptDir, 'xynigo_dxm_fulfillment_timing.user.js');
const rawUrl = 'https://raw.githubusercontent.com/wrangler1024/crossborder-userscripts/main/scripts/dxm-fulfillment-timing/xynigo_dxm_fulfillment_timing.user.js';

const header = `// ==UserScript==
// @name         Xynigo 店小秘履约时效助手
// @namespace    https://github.com/wrangler1024/crossborder-userscripts
// @version      ${manifest.version}
// @description  在店小秘物流追踪-已签收面板一键统计备货/揽收/尾程/运输/履约时效,监控上网早于下单的发货异常,支持六维筛选与 CSV 导出;全程只读。
// @author       Samforo
// @homepageURL  https://github.com/wrangler1024/crossborder-userscripts/tree/main/scripts/dxm-fulfillment-timing
// @supportURL   https://github.com/wrangler1024/crossborder-userscripts/issues
// @match        https://dianxiaomi.com/web/otherFeatures/tracking*
// @match        https://*.dianxiaomi.com/web/otherFeatures/tracking*
// @icon         https://raw.githubusercontent.com/wrangler1024/crossborder-userscripts/main/extensions/xynigo-dxm-fulfillment-timing/icons/icon128.png
// @grant        GM_getValue
// @grant        GM_setValue
// @grant        GM_deleteValue
// @grant        GM_listValues
// @run-at       document-start
// @downloadURL  ${rawUrl}
// @updateURL    ${rawUrl}
// ==/UserScript==`;

const output = [
  header,
  '',
  '// Generated from the shared Manifest V3 source. Do not edit this file by hand.',
  runtime,
  '',
  `globalThis.XftFulfillmentUserscriptRuntime.boot(globalThis, ${JSON.stringify({
    css,
    injectSource: inject,
    version: manifest.version,
  })}, globalThis.XftFulfillmentUserscriptRuntime.browserAdapters());`,
  '',
  core,
  '',
  content,
  '',
].join('\n');

fs.writeFileSync(outputPath, output, 'utf8');
process.stdout.write(`${outputPath}\n`);
