'use strict';

const fs = require('node:fs');
const path = require('node:path');

const scriptDir = __dirname;
const repoRoot = path.resolve(scriptDir, '..', '..');
const extensionDir = path.join(repoRoot, 'extensions', 'xynigo-dxm-purchase-assistant');
const manifest = JSON.parse(fs.readFileSync(path.join(extensionDir, 'manifest.json'), 'utf8'));
const runtime = fs.readFileSync(path.join(scriptDir, 'userscript-runtime.js'), 'utf8').trim();
const core = fs.readFileSync(path.join(extensionDir, 'src', 'core.js'), 'utf8').trim();
const content = fs.readFileSync(path.join(extensionDir, 'src', 'content.js'), 'utf8').trim();
const css = fs.readFileSync(path.join(extensionDir, 'src', 'content.css'), 'utf8');
const outputPath = path.join(scriptDir, 'xynigo_dxm_purchase_assistant.user.js');
const rawUrl = 'https://raw.githubusercontent.com/wrangler1024/crossborder-userscripts/main/scripts/dxm-purchase-assistant/xynigo_dxm_purchase_assistant.user.js';

const header = `// ==UserScript==
// @name         Xynigo 店小秘运营采购助手
// @namespace    https://github.com/wrangler1024/crossborder-userscripts
// @version      ${manifest.version}
// @description  在店小秘待审核订单详情中录入逐商品采购信息、计算预估利润，并在提交采购单后解锁审核。
// @author       Samforo
// @homepageURL  https://github.com/wrangler1024/crossborder-userscripts/tree/main/scripts/dxm-purchase-assistant
// @supportURL   https://github.com/wrangler1024/crossborder-userscripts/issues
// @match        https://dianxiaomi.com/*
// @match        https://*.dianxiaomi.com/*
// @icon         https://raw.githubusercontent.com/wrangler1024/crossborder-userscripts/main/assets/xynigo-mascot.png
// @grant        GM_getValue
// @grant        GM_setValue
// @grant        GM_deleteValue
// @grant        GM_listValues
// @grant        GM_addStyle
// @grant        GM_registerMenuCommand
// @run-at       document-start
// @downloadURL  ${rawUrl}
// @updateURL    ${rawUrl}
// ==/UserScript==`;

const output = [
  header,
  '',
  '// Generated from the shared Manifest V3 source. Do not edit this file by hand.',
  runtime,
  '',
  `globalThis.XynigoDxmUserscriptRuntime.boot(globalThis, ${JSON.stringify(css)}, ${JSON.stringify(manifest.version)}, globalThis.XynigoDxmUserscriptRuntime.browserAdapters());`,
  '',
  core,
  '',
  content,
  '',
].join('\n');

fs.writeFileSync(outputPath, output, 'utf8');
process.stdout.write(`${outputPath}\n`);
