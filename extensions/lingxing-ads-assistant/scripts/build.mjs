import fs from 'node:fs/promises';
import path from 'node:path';
import {APP_VERSION} from '../src/model.mjs';
import {DETAIL_TEMPLATE_FILENAME} from '../src/template-spec.mjs';
import {moduleRoot as root} from './bundle.mjs';
import {extensionBundle} from './extension-bundle.mjs';
const {source,legacySource,manifest,templateBytes}=await extensionBundle();
const extension=path.join(root,'dist/extension');
await fs.rm(extension,{recursive:true,force:true});
await fs.mkdir(extension,{recursive:true});
await fs.writeFile(path.join(extension,'content.js'),source);
await fs.writeFile(path.join(extension,'legacy-entry.js'),legacySource);
await fs.writeFile(path.join(extension,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');
for(const file of ['popup.html','popup.css','popup.js','storage-bridge.js','launcher-bridge.js','launcher-settings.mjs','background.mjs','storage-service.mjs'])await fs.copyFile(path.join(root,'extension',file),path.join(extension,file));
await fs.writeFile(path.join(extension,'popup.html'),(await fs.readFile(path.join(root,'extension/popup.html'),'utf8')).replace('{{VERSION}}',APP_VERSION));
await fs.copyFile(path.join(root,'vendor/LICENSE-SheetJS.txt'),path.join(extension,'LICENSE-SheetJS.txt'));
await fs.writeFile(path.join(extension,DETAIL_TEMPLATE_FILENAME),templateBytes);
await fs.writeFile(path.join(root,'dist',DETAIL_TEMPLATE_FILENAME),templateBytes);
console.log(`Built dist/extension (Manifest V3, ${APP_VERSION}, ${Buffer.byteLength(source)} bytes of local code)`);
